"""Generate docs/reference/configuration.md and docs/reference/api.md from the code.

Run: uv run python scripts/gen_reference.py        (CI runs it with --check to catch stale docs)
"""

from __future__ import annotations

import ast
import inspect
import json
import re
import sys
import typing
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from fastapi.routing import APIRoute  # noqa: E402

from myelinate import config  # noqa: E402
from myelinate.config import Settings  # noqa: E402

HEADER = "<!-- Generated by scripts/gen_reference.py — do not edit by hand. -->\n\n"


def _type(ann: object) -> str:
    s = str(ann).replace("typing.", "").replace("pydantic.types.", "").replace("<class '", "").replace("'>", "")
    return s.replace("NoneType", "None")


def configuration() -> str:
    src = Path(inspect.getsourcefile(config)).read_text()  # type: ignore[arg-type]
    lines = src.splitlines()
    tree = ast.parse(src)
    cls = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "Settings")
    rows: list[tuple[str, str, str, str, str]] = []
    section = "General"
    pending: list[str] = []
    prev_end = cls.body[0].lineno - 1
    for node in cls.body:
        if not isinstance(node, ast.AnnAssign) or not isinstance(node.target, ast.Name):
            prev_end = getattr(node, "end_lineno", prev_end)
            continue
        between = lines[prev_end:node.lineno - 1]
        pending = []
        for ln in between:
            t = ln.strip()
            m = re.match(r"#\s*-+\s*(.+?)\s*-+$", t)
            if m:
                section = m.group(1)
            elif t.startswith("#"):
                pending.append(t.lstrip("# ").strip())
        name = node.target.id
        if name == "model_config":
            prev_end = node.end_lineno or node.lineno
            continue
        seg = "\n".join(lines[node.lineno - 1:node.end_lineno])
        trailing = seg.split("#", 1)[1].strip() if "#" in lines[node.end_lineno - 1] else ""
        desc = " ".join(pending + ([trailing] if trailing else []))
        field = Settings.model_fields[name]
        default = field.get_default(call_default_factory=True)
        env = f"MYELINATE_{name.upper()}"
        if name == "anthropic_api_key":
            env = "MYELINATE_ANTHROPIC_API_KEY or ANTHROPIC_API_KEY"
        dflt = "—" if default is None else ("`(secret)`" if "Secret" in _type(field.annotation) and default
                                           else f"`{json.dumps(default) if isinstance(default, list) else default}`")
        rows.append((section, env, _type(field.annotation).replace(" | ", " or "), dflt, desc.replace("|", "\\|")))
        prev_end = node.end_lineno or node.lineno

    out = [HEADER, "# Configuration reference\n\n",
           "Every setting is an environment variable (or a line in `.env`). Names are `MYELINATE_` plus the upper-case "
           "field name. Lists take JSON, for example `MYELINATE_CORS_ORIGINS='[\"https://app.example.com\"]'`.\n"]
    current = None
    for section, env, typ, dflt, desc in rows:
        if section != current:
            current = section
            out.append(f"\n## {section}\n\n| Variable | Type | Default | Description |\n|---|---|---|---|\n")
        out.append(f"| `{env}` | `{typ}` | {dflt} | {desc} |\n")
    return "".join(out)


def _scope(route: APIRoute) -> str:
    for dep in route.dependant.dependencies:
        if dep.call is not None and dep.call.__name__ == "dep":
            return inspect.getclosurevars(dep.call).nonlocals.get("scope", "—")
    return "none"


def api() -> tuple[str, dict]:
    from myelinate.gateway.app import create_app

    app = create_app(Settings(env="dev", llm_provider="none", database_url="sqlite+aiosqlite:///:memory:"))
    spec = app.openapi()
    groups: dict[str, list[str]] = {}
    for r in app.routes:
        if not isinstance(r, APIRoute) or not r.include_in_schema:
            continue
        tag = (r.tags or ["other"])[0]
        doc = inspect.getdoc(r.endpoint) or ""
        summary = doc.splitlines()[0] if doc else r.name.replace("_", " ").capitalize()
        ann = r.body_field.field_info.annotation if r.body_field is not None else None
        body = ""
        if ann is not None:
            body = (f"list[{typing.get_args(ann)[0].__name__}]" if typing.get_origin(ann) is list
                    else getattr(ann, "__name__", ""))
        resp = getattr(r.response_model, "__name__", "") if r.response_model else ""
        if typing.get_origin(r.response_model) is list:
            resp = f"list[{typing.get_args(r.response_model)[0].__name__}]"
        for m in sorted(r.methods - {"HEAD"}):
            groups.setdefault(tag, []).append(
                f"| `{m}` | `{r.path}` | `{_scope(r)}` | {summary} | {('`' + body + '`') if body else ''} | "
                f"{('`' + resp + '`') if resp else ''} |\n")
    titles = {"loop": "Learning loop", "skills": "Skills", "memory": "Memory & profiles",
              "governance": "Governance & insights", "admin": "Administration"}
    out = [HEADER, "# REST API reference\n\n",
           "All endpoints take `Authorization: Bearer <token>` (a tenant API key, an OIDC token, or the bootstrap admin "
           "key plus `X-Tenant-Id`). The **scope** column is the permission the token needs; see "
           "[Security](../operations/security.md). Interactive docs are served at `/docs` and the machine-readable "
           "spec at `/openapi.json` ([download](openapi.json)).\n\n"
           "Operational endpoints without auth: `GET /healthz`, `GET /readyz`, `GET /metrics`. The MCP endpoint is "
           "`/mcp` (see [MCP](../integrations/mcp.md)).\n"]
    for tag in ("loop", "skills", "memory", "governance", "admin"):
        if tag in groups:
            out.append(f"\n## {titles[tag]}\n\n| Method | Path | Scope | Description | Body | Response |\n"
                       "|---|---|---|---|---|---|\n")
            out += groups[tag]
    out.append("\n## Schemas\n\nRequest and response models, from the OpenAPI spec.\n")
    for name, schema in sorted(spec.get("components", {}).get("schemas", {}).items()):
        if name.startswith(("HTTPValidationError", "ValidationError")):
            continue
        props = schema.get("properties", {})
        req = set(schema.get("required", []))
        out.append(f"\n### `{name}`\n\n")
        if schema.get("description"):
            out.append(schema["description"].strip() + "\n\n")
        out.append("| Field | Type | Required |\n|---|---|---|\n")
        for p, v in props.items():
            t = v.get("type") or ("ref " + v["$ref"].split("/")[-1] if "$ref" in v else
                                  " \\| ".join(x.get("type", x.get("$ref", "").split("/")[-1]) for x in v.get("anyOf", [])))
            out.append(f"| `{p}` | {t} | {'yes' if p in req else ''} |\n")
    return "".join(out), spec


def main() -> int:
    check = "--check" in sys.argv
    api_md, spec = api()
    files = {ROOT / "docs/reference/configuration.md": configuration(),
             ROOT / "docs/reference/api.md": api_md,
             ROOT / "docs/reference/openapi.json": json.dumps(spec, indent=1, sort_keys=True) + "\n"}
    stale = []
    for path, content in files.items():
        if check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        print("stale generated docs (run `uv run python scripts/gen_reference.py`):", *stale, sep="\n  ")
        return 1
    print("reference docs", "up to date" if check else "written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
